"""Ranking-eval runner (Step 5/5b): score retrieve -> [rerank] -> rank on the golden set.

    uv run python -m evaluation.ranking.run     # needs Qdrant up + OPENAI_API_KEY

Runs the pipeline both WITHOUT and WITH the cross-encoder reranker and writes an A/B
comparison to docs/eval-baseline.md. Prints both aggregates. This is the go/no-go gate.
"""

from __future__ import annotations

import json
import statistics
import sys
from pathlib import Path

from pydantic import BaseModel

from core.config import get_settings
from evaluation.ranking.metrics import ndcg_at_k, recall_at_k, reciprocal_rank
from recommender.service import recommend
from retrieval.index import load_catalog
from retrieval.rerank import CrossEncoderReranker, Reranker
from retrieval.store import QdrantHybridStore

GOLDEN_PATH = Path(__file__).parent / "golden_set.json"
REPORT_OUT = Path("docs/eval-baseline.md")
RETRIEVE_K = 9  # rank the whole catalog so NDCG/MRR see the full ordering
METRICS = ("recall@3", "recall@5", "ndcg@3", "ndcg@5", "mrr")


class GoldenQuery(BaseModel):
    query: str
    relevant_ids: list[str]
    tier: str
    rationale: str


class EvalRow(BaseModel):
    query: str
    tier: str
    n_rel: int
    recall_at_3: float
    recall_at_5: float
    ndcg_at_3: float
    ndcg_at_5: float
    rr: float
    top3: list[str]


def load_golden(path: Path = GOLDEN_PATH) -> list[GoldenQuery]:
    raw = json.loads(path.read_text(encoding="utf-8"))
    return [GoldenQuery.model_validate(item) for item in raw]


def evaluate(
    golden: list[GoldenQuery],
    store: QdrantHybridStore,
    id_to_title: dict[str, str],
    reranker: Reranker | None = None,
) -> list[EvalRow]:
    rows: list[EvalRow] = []
    for item in golden:
        result = recommend(item.query, store, k=RETRIEVE_K, reranker=reranker)
        ranked_ids = [p.product_id for p in result.products]
        relevant = set(item.relevant_ids)
        rows.append(
            EvalRow(
                query=item.query,
                tier=item.tier,
                n_rel=len(relevant),
                recall_at_3=recall_at_k(ranked_ids, relevant, 3),
                recall_at_5=recall_at_k(ranked_ids, relevant, 5),
                ndcg_at_3=ndcg_at_k(ranked_ids, relevant, 3),
                ndcg_at_5=ndcg_at_k(ranked_ids, relevant, 5),
                rr=reciprocal_rank(ranked_ids, relevant),
                top3=[id_to_title.get(i, i) for i in ranked_ids[:3]],
            )
        )
    return rows


def _mean(values: list[float]) -> float:
    return round(statistics.fmean(values), 4) if values else 0.0


def _agg(rows: list[EvalRow]) -> dict[str, float]:
    return {
        "recall@3": _mean([r.recall_at_3 for r in rows]),
        "recall@5": _mean([r.recall_at_5 for r in rows]),
        "ndcg@3": _mean([r.ndcg_at_3 for r in rows]),
        "ndcg@5": _mean([r.ndcg_at_5 for r in rows]),
        "mrr": _mean([r.rr for r in rows]),
    }


def build_report(base_rows: list[EvalRow], rerank_rows: list[EvalRow]) -> str:
    base, rer = _agg(base_rows), _agg(rerank_rows)
    attribute = _agg([r for r in rerank_rows if r.tier == "attribute"])
    semantic = _agg([r for r in rerank_rows if r.tier == "semantic"])
    header = "| pipeline | " + " | ".join(METRICS) + " |"
    sep = "|" + "---|" * (len(METRICS) + 1)

    lines: list[str] = [
        "# Ranking Eval Baseline (Steps 5 + 5b)",
        "",
        "> Generated by `evaluation.ranking.run`. Pipeline: Qdrant hybrid retrieval ->",
        "> [cross-encoder rerank] -> rating-aware ranking. Golden set:",
        "> `packages/evaluation/ranking/golden_set.json`.",
        "",
        "## A/B: hybrid-only vs + reranker (mean over all queries)",
        "",
        header,
        sep,
        "| hybrid only | " + " | ".join(f"{base[m]}" for m in METRICS) + " |",
        "| **+ reranker** | " + " | ".join(f"**{rer[m]}**" for m in METRICS) + " |",
        "| Δ (rerank − base) | " + " | ".join(f"{rer[m] - base[m]:+.4f}" for m in METRICS) + " |",
        "",
        "## + reranker, per tier",
        "",
        "| tier | n | recall@3 | recall@5 | ndcg@3 | ndcg@5 | mrr |",
        "|---|---|---|---|---|---|---|",
        f"| attribute | {sum(r.tier == 'attribute' for r in rerank_rows)} | "
        f"{attribute['recall@3']} | {attribute['recall@5']} | {attribute['ndcg@3']} | "
        f"{attribute['ndcg@5']} | {attribute['mrr']} |",
        f"| semantic | {sum(r.tier == 'semantic' for r in rerank_rows)} | "
        f"{semantic['recall@3']} | {semantic['recall@5']} | {semantic['ndcg@3']} | "
        f"{semantic['ndcg@5']} | {semantic['mrr']} |",
        "",
        "## + reranker, per query",
        "",
        "| query | tier | #rel | R@3 | NDCG@3 | RR | top-3 returned |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in rerank_rows:
        top3 = "; ".join(t[:28] for t in r.top3)
        lines.append(
            f"| {r.query} | {r.tier} | {r.n_rel} | {r.recall_at_3:.2f} "
            f"| {r.ndcg_at_3:.2f} | {r.rr:.2f} | {top3} |"
        )

    lines += [
        "",
        "## Methodology & honest caveats",
        "",
        "- **Catalog = 9 products, one category (audio).** Recall@k is near-trivial at this "
        "size; **NDCG/MRR (ordering quality) are the meaningful signals.** Sanity check, not "
        "a benchmark.",
        "- **Relevance labels are attribute-based** (brand, wired/wireless, neckband/TWS, "
        "bass-in-name) to avoid circularity. `attribute`-tier is objective; `semantic`-tier "
        "(bass/budget) is softer and documented per query in the golden set.",
        f"- Reranker: cross-encoder `{get_settings().reranker_model}` (local, fastembed); "
        "logit -> sigmoid -> relevance feeding the ranking blend.",
        "",
        "## Conclusion: reranker OFF by default",
        "",
        "- The cross-encoder reranker improved MRR "
        f"({base['mrr']} -> {rer['mrr']}) but **regressed NDCG@3** "
        f"({base['ndcg@3']} -> {rer['ndcg@3']}) and **Recall@3** "
        f"({base['recall@3']} -> {rer['recall@3']}), and did **not** lift the "
        "semantic/bass tier. Kept behind a flag (`rerank_enabled`, default False) per "
        "Decision 3 — measure, don't assume.",
        "",
        "## CI regression gate (production default = hybrid-only)",
        "",
        f"- Gate: **NDCG@3 ≥ {base['ndcg@3']} − 0.05** and **MRR ≥ {base['mrr']} − 0.05**.",
        "- Re-baseline whenever retrieval, ranking weights, or the golden set change.",
    ]
    return "\n".join(lines) + "\n"


def run() -> list[EvalRow]:
    settings = get_settings()
    if not settings.openai_api_key:
        sys.exit("OPENAI_API_KEY not set — add it to .env before running the ranking eval.")

    catalog = load_catalog()
    id_to_title = {p.product_id: p.title for p in catalog}
    store = QdrantHybridStore()
    store.index(catalog)  # re-index for a reproducible baseline

    golden = load_golden()
    base_rows = evaluate(golden, store, id_to_title, reranker=None)
    rerank_rows = evaluate(golden, store, id_to_title, reranker=CrossEncoderReranker())

    REPORT_OUT.parent.mkdir(parents=True, exist_ok=True)
    REPORT_OUT.write_text(build_report(base_rows, rerank_rows), encoding="utf-8")

    base, rer = _agg(base_rows), _agg(rerank_rows)
    print(f"hybrid only : NDCG@3={base['ndcg@3']}  MRR={base['mrr']}  Recall@3={base['recall@3']}")
    print(f"+ reranker  : NDCG@3={rer['ndcg@3']}  MRR={rer['mrr']}  Recall@3={rer['recall@3']}")
    print(f"wrote {REPORT_OUT}")
    return rerank_rows


if __name__ == "__main__":
    run()
