"""Aggregator ranking eval: scores the path users actually hit.

    uv run python -m evaluation.aggregator.run          # offline: costs 0 SerpApi searches

Why this exists: the other evals (`evaluation.ranking`, `evaluation.ragas`) score the static
9-product audio catalog reached via /recommend and /chat. But the shipped UI calls **/aggregate**
— live Google-Shopping offers. So the recorded quality baselines covered a code path no user
takes, and the product's real ranking had *no* quality gate at all.

**What it measures.** The aggregator's whole value claim is: *"the order isn't Google's order —
we re-rank on evidence (rating weighted by review volume)."* That claim is testable, so this eval
tests exactly it, comparing two orderings of the same offers:

    baseline : Google Shopping's own order (the `position` field)
    ours     : rank_offers(...) — the shipped ranking blend

A "good" offer is defined **objectively and independently of our ranker** (no circularity):
    rating >= 4.3  AND  review_count >= 100      (well-rated AND actually corroborated)
A thin 5-star with 3 reviews is deliberately NOT good — that is the failure mode the
volume-confidence term exists to prevent.

If our NDCG/MRR does not beat Google's order, the product has no reason to exist — so this is the
number to defend, and the CI gate protects it.

Offers come from recorded SerpApi responses in ``fixtures/`` (real data, captured once), so the
eval is reproducible, runs in CI, and never spends a metered search.
"""

from __future__ import annotations

import json
import statistics
from pathlib import Path

from pydantic import BaseModel

from core.models import Offer
from evaluation.ranking.metrics import ndcg_at_k, recall_at_k, reciprocal_rank
from recommender.offer_ranking import rank_offers
from sources.serpapi_source import parse_shopping_results

FIXTURES = Path(__file__).parent / "fixtures"
REPORT_OUT = Path("reports/aggregator-eval.md")  # reports/ is tracked; docs/ is gitignored
BASELINE_PATH = Path(__file__).parent / "baseline.json"

# Objective "good offer" definition — set WITHOUT reference to how our ranker scores.
MIN_GOOD_RATING = 4.3
MIN_GOOD_REVIEWS = 100


class EvalRow(BaseModel):
    query: str
    n_offers: int
    n_good: int
    google_ndcg_at_3: float
    google_mrr: float
    ours_ndcg_at_3: float
    ours_mrr: float
    ours_recall_at_3: float


def is_good(offer: Offer) -> bool:
    """Well-rated AND corroborated by real review volume."""
    return (
        offer.rating is not None
        and offer.rating >= MIN_GOOD_RATING
        and offer.review_count >= MIN_GOOD_REVIEWS
    )


def load_fixtures() -> dict[str, list[Offer]]:
    fixtures: dict[str, list[Offer]] = {}
    for path in sorted(FIXTURES.glob("*.json")):
        payload = json.loads(path.read_text(encoding="utf-8"))
        query = (payload.get("search_parameters") or {}).get("q") or path.stem
        fixtures[query] = parse_shopping_results(payload)
    return fixtures


def evaluate() -> list[EvalRow]:
    rows: list[EvalRow] = []
    for query, offers in load_fixtures().items():
        relevant = {o.product_id for o in offers if is_good(o)}
        if not relevant:
            continue  # nothing to score against

        google_order = [o.product_id for o in sorted(offers, key=lambda o: o.position or 999)]
        ours_order = [r.offer.product_id for r in rank_offers(offers)]

        rows.append(
            EvalRow(
                query=query,
                n_offers=len(offers),
                n_good=len(relevant),
                google_ndcg_at_3=ndcg_at_k(google_order, relevant, 3),
                google_mrr=reciprocal_rank(google_order, relevant),
                ours_ndcg_at_3=ndcg_at_k(ours_order, relevant, 3),
                ours_mrr=reciprocal_rank(ours_order, relevant),
                ours_recall_at_3=recall_at_k(ours_order, relevant, 3),
            )
        )
    return rows


def _mean(values: list[float]) -> float:
    return round(statistics.fmean(values), 4) if values else 0.0


def aggregate_metrics(rows: list[EvalRow]) -> dict[str, float]:
    return {
        "google_ndcg_at_3": _mean([r.google_ndcg_at_3 for r in rows]),
        "google_mrr": _mean([r.google_mrr for r in rows]),
        "ndcg_at_3": _mean([r.ours_ndcg_at_3 for r in rows]),
        "mrr": _mean([r.ours_mrr for r in rows]),
        "recall_at_3": _mean([r.ours_recall_at_3 for r in rows]),
    }


def build_report(rows: list[EvalRow], metrics: dict[str, float]) -> str:
    lift_ndcg = metrics["ndcg_at_3"] - metrics["google_ndcg_at_3"]
    lift_mrr = metrics["mrr"] - metrics["google_mrr"]
    lines: list[str] = [
        "# Aggregator Ranking Baseline — the SHIPPED /aggregate path",
        "",
        "> Generated by `evaluation.aggregator.run`. Offline, from recorded SerpApi responses:",
        "> **0 metered searches**. This is the path the UI actually calls; the other baselines",
        "> (`ranking-eval.md`, `answer-quality-eval.md`) score the static audio catalog.",
        "",
        "## Does our ranking beat Google's own order?",
        "",
        "| ordering | NDCG@3 | MRR |",
        "|---|---|---|",
        f"| Google Shopping (position) | {metrics['google_ndcg_at_3']} | {metrics['google_mrr']} |",
        f"| **Ours (rating × volume blend)** | **{metrics['ndcg_at_3']}** | **{metrics['mrr']}** |",
        f"| **Lift** | **{lift_ndcg:+.4f}** | **{lift_mrr:+.4f}** |",
        "",
        f"Recall@3 (ours): {metrics['recall_at_3']}",
        "",
        "## Per query",
        "",
        "| query | offers | good | Google NDCG@3 | Ours NDCG@3 | Google MRR | Ours MRR |",
        "|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        lines.append(
            f"| {r.query} | {r.n_offers} | {r.n_good} | {r.google_ndcg_at_3:.2f} "
            f"| {r.ours_ndcg_at_3:.2f} | {r.google_mrr:.2f} | {r.ours_mrr:.2f} |"
        )
    lines += [
        "",
        "## Methodology (and why it isn't circular)",
        "",
        f"- A **good** offer is defined independently of our ranker: `rating >= {MIN_GOOD_RATING}` "
        f"**and** `review_count >= {MIN_GOOD_REVIEWS}` — well-rated *and* corroborated. A thin "
        "5-star with 3 reviews is deliberately not 'good': that is precisely the trap the "
        "volume-confidence term exists to avoid.",
        "- Offers are real, captured from live Google Shopping across 4 categories "
        "(audio, footwear, peripherals) — which also demonstrates the aggregator is genuinely "
        "multi-category, not audio-only.",
        "- **Honest limitation:** this scores *ranking* only. It does not judge the LLM's written "
        "reasons (that is `evaluation.ragas`), and 4 recorded queries is a sanity check, not a "
        "benchmark.",
    ]
    return "\n".join(lines) + "\n"


def run() -> dict[str, float]:
    rows = evaluate()
    metrics = aggregate_metrics(rows)
    REPORT_OUT.parent.mkdir(parents=True, exist_ok=True)
    REPORT_OUT.write_text(build_report(rows, metrics), encoding="utf-8")

    print(
        f"queries={len(rows)}  "
        f"google: NDCG@3={metrics['google_ndcg_at_3']} MRR={metrics['google_mrr']}  |  "
        f"ours: NDCG@3={metrics['ndcg_at_3']} MRR={metrics['mrr']}"
    )
    print(
        f"lift: NDCG@3={metrics['ndcg_at_3'] - metrics['google_ndcg_at_3']:+.4f}  "
        f"MRR={metrics['mrr'] - metrics['google_mrr']:+.4f}"
    )
    print(f"wrote {REPORT_OUT}")
    return metrics


if __name__ == "__main__":
    run()
